function jitter(value: number, pct = 0.004) {
  const delta = value * pct * (Math.random() * 2 - 1);
  return Number((value + delta).toFixed(4));
}

export function livePrice(def: EtfDefinition): number {
  return jitter(def.basePrice);
}

export function findEtf(ticker: string): EtfDefinition | undefined {
  return ETF_CATALOG.find((e) => e.ticker.toLowerCase() === ticker.toLowerCase());
}

export function isAvailableInCountry(def: EtfDefinition, country?: string | null): boolean {
  if (!def.restrictedToCountries || def.restrictedToCountries.length === 0) return true;
  if (!country) return true;
  return def.restrictedToCountries.includes(country.toUpperCase());
}
